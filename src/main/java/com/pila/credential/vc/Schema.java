package com.pila.credential.vc;

/**
 * Schema represents a credential schema with an ID and type.
 */
public class Schema {
    private String id;
    private String type;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }
}
