package com.pila.credential.common.jsonmap;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.pila.credential.common.verificationmethod.DIDDocument;
import com.pila.credential.common.verificationmethod.StaticDocumentResolver;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * Proofs generated by go-credential-sdk's own signing code (see go-fixtures/legacy-jws-jwtproof.json:
 * legacy hex proof over numeric claims, JsonWebSignature2020 RS/PS/ES, JwtProof2020 and an
 * rdfc proof carrying id/expires/nonce/array domain). Each carries Go's own verdict, and Java must agree.
 */
class GoLegacyAndJwsFixturesTest {

    private static final ObjectMapper MAPPER = new ObjectMapper()
            .configure(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES, false);

    @TestFactory
    List<DynamicTest> javaAgreesWithGo() throws Exception {
        JsonNode all;
        try (InputStream in = getClass().getResourceAsStream("/go-fixtures/legacy-jws-jwtproof.json")) {
            all = MAPPER.readTree(in);
        }
        List<DynamicTest> tests = new ArrayList<>();
        for (JsonNode fx : all) {
            String name = fx.get("name").asText();
            boolean goVerified = fx.get("goVerified").asBoolean();
            tests.add(DynamicTest.dynamicTest(name, () -> {
                JSONMap m = new JSONMap(MAPPER.convertValue(fx.get("credential"), new TypeReference<Map<String, Object>>() {
                }));
                DIDDocument doc = MAPPER.treeToValue(fx.get("didDocument"), DIDDocument.class);
                boolean ok;
                try {
                    ok = m.verifyProof(new StaticDocumentResolver(doc));
                } catch (Exception e) {
                    ok = false;
                }
                assertEquals(goVerified, ok, name);
            }));
        }
        return tests;
    }
}
